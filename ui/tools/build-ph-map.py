"""Build assets/ph-provinces.js (Presence map) from faeldon/philippines-json-maps (MIT).

1. Download the low-resolution province files (one per region, ~600 KB in total):
     latest/geojson/regions/lowres/provdists-region-*.0.001.json
   from https://github.com/faeldon/philippines-json-maps into a folder.
2. python3 ui/tools/build-ph-map.py <that folder> > assets/ph-provinces.js

Projection: equirectangular, longitude scaled by cos(mid-latitude), fitted to 1000 units tall.
Rings under ~1.2 units across (islets invisible at page size) are dropped.
"""
import glob, json, math, os, sys

src = sys.argv[1]
feats = [ft for f in sorted(glob.glob(os.path.join(src, "provdists-region-*.json"))) for ft in json.load(open(f))["features"]]

def rings(g):
    return g["coordinates"] if g["type"] == "Polygon" else [r for poly in g["coordinates"] for r in poly]

pts = [p for ft in feats for r in rings(ft["geometry"]) for p in r]
lon0, lon1 = min(p[0] for p in pts), max(p[0] for p in pts)
lat0, lat1 = min(p[1] for p in pts), max(p[1] for p in pts)
H = 1000.0
k = H / (lat1 - lat0)
c = math.cos(math.radians((lat0 + lat1) / 2))
W = (lon1 - lon0) * c * k

def path(g):
    out = []
    for poly in ([g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]):
        for ring in poly:
            seg, last = [], None
            for x, y in ring:
                q = (round((x - lon0) * c * k, 1), round((lat1 - y) * k, 1))
                if q != last:
                    seg.append(q); last = q
            if len(seg) < 3:
                continue
            xs, ys = [p[0] for p in seg], [p[1] for p in seg]
            if max(xs) - min(xs) < 1.2 and max(ys) - min(ys) < 1.2:
                continue
            out.append("M" + " ".join(f"{x:g} {y:g}" for x, y in seg) + "Z")
    return "".join(out)

provs = []
for ft in feats:
    p = ft["properties"]
    name = p["adm2_en"].replace(" (Not a Province)", "")
    if name.startswith("NCR"):
        name = "Metro Manila · " + ("City of Manila" if "City of Manila" in name else name.split(", ")[-1])
    provs.append({"psgc": p["adm2_psgc"], "region": p["adm1_psgc"], "name": name, "d": path(ft["geometry"])})

# Region names by PSGC code (the source files carry codes only at this level).
REGIONS = {
    100000000: "Ilocos Region (Region I)", 200000000: "Cagayan Valley (Region II)",
    300000000: "Central Luzon (Region III)", 400000000: "CALABARZON (Region IV-A)",
    500000000: "Bicol Region (Region V)", 600000000: "Western Visayas (Region VI)",
    700000000: "Central Visayas (Region VII)", 800000000: "Eastern Visayas (Region VIII)",
    900000000: "Zamboanga Peninsula (Region IX)", 1000000000: "Northern Mindanao (Region X)",
    1100000000: "Davao Region (Region XI)", 1200000000: "SOCCSKSARGEN (Region XII)",
    1300000000: "National Capital Region", 1400000000: "Cordillera Administrative Region",
    1600000000: "Caraga (Region XIII)", 1700000000: "MIMAROPA Region",
    1800000000: "Negros Island Region", 1900000000: "Bangsamoro (BARMM)",
}
source = "faeldon/philippines-json-maps (MIT), PSGC 3Q 2026, low resolution"
data = {"source": source, "viewBox": f"0 0 {W:.0f} {H:.0f}", "regions": {str(k): v for k, v in REGIONS.items()}, "provinces": provs}
sys.stdout.write("/* Province shapes for the Presence map, pre-projected to SVG paths (equirectangular,\n"
                 " * scaled for latitude). Source: " + source + ".\n"
                 " * Generated by ui/tools/build-ph-map.py; don't edit by hand. */\n"
                 "window.AB_MAP = " + json.dumps(data, separators=(",", ":")) + ";\n")
